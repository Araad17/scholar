const LanguageContext = createContext<{ language: Language; toggle: () => void } | null>(null);

export function translate(text: string): string {
  if (activeLanguage !== 'en') return text;
  return translations[text] ?? text;
}

export const currentLanguage = () => activeLanguage;
export const formatNumber = (value: number) => value.toLocaleString(activeLanguage === 'fa' ? 'fa-AF' : 'en-US');
export const percentSign = () => activeLanguage === 'fa' ? '٪' : '%';

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    try {
      return window.localStorage.getItem(LANGUAGE_KEY) === 'en' ? 'en' : 'fa';
    } catch {
      return 'fa';
    }
  });
  activeLanguage = language;

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'fa' ? 'rtl' : 'ltr';
    try {
      window.localStorage.setItem(LANGUAGE_KEY, language);
    } catch {
      // The current selection remains active for this page session.
    }
  }, [language]);

  const value = useMemo(() => ({
    language,
    toggle: () => setLanguage((current) => current === 'fa' ? 'en' : 'fa'),
  }), [language]);

  return (
    <LanguageContext.Provider value={value}>
      <div lang={language} dir={language === 'fa' ? 'rtl' : 'ltr'} className="min-h-screen">
        {children}
      </div>
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}

export function LanguageToggle() {
  const { language, toggle } = useLanguage();
  return (
    <button
      type="button"
      onClick={toggle}
      className="rounded-md border border-current/20 px-3 py-2 text-xs font-bold transition hover:bg-white/10"
      aria-label={language === 'fa' ? 'Switch language to English' : 'تغییر زبان به فارسی'}
    >
      {language === 'fa' ? 'EN' : 'فا'}
    </button>
  );
}
